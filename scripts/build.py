"""Build the public offline atlas from this checkout only (Python3.12+, stdlib).

No research workspace, Hermes installation, Node.js or network is required.
The committed root index.html is generated by this module, not edited directly.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CSS_FILES = ('style.css', 'timeline.css', 'graph_time.css')
JS_FILES = ('graph_routes.js', 'atlas.js', 'timeline.js', 'graph_time.js', 'status_popover.js', 'timeline_host.js')
MIME_SIGNATURES = {'image/jpeg': b'\xff\xd8\xff', 'image/png': b'\x89PNG\r\n\x1a\n'}


class BuildError(ValueError):
    """Invalid source data; the existing generated page must remain untouched."""


def safe_json(value: Any) -> str:
    """Escape inline-script delimiters without changing their decoded values."""
    return (json.dumps(value, ensure_ascii=False, separators=(',', ':'), allow_nan=False)
            .replace('&', '\\u0026').replace('<', '\\u003c').replace('>', '\\u003e')
            .replace('\u2028', '\\u2028').replace('\u2029', '\\u2029'))


def embed_documents(model: dict, root: Path = ROOT) -> dict:
    """Replace approved image references by offline data URIs, preserving key order.

    This mutates its supplied freshly loaded model, never data/atlas.json.
    Reject absolute paths, traversal, symlinks escaping assets/, and MIME confusion.
    """
    root = Path(root).resolve()
    allowed = root / 'assets'
    if not isinstance(model, dict) or not isinstance(model.get('documents', []), list):
        raise BuildError('Atlas data must be an object with a documents array')
    documents = []
    for number, doc in enumerate(model.get('documents', []), 1):
        if not isinstance(doc, dict):
            raise BuildError(f'documents[{number}] must be an object')
        asset = doc.get('asset')
        mime = doc.get('media_type')
        if not isinstance(asset, str) or Path(asset).is_absolute() or '..' in Path(asset).parts:
            raise BuildError(f'documents[{number}].asset must be a relative path inside assets/')
        if not asset.startswith('assets/') or not isinstance(mime, str) or mime not in MIME_SIGNATURES:
            raise BuildError(f'documents[{number}] has an unsupported asset path or media_type')
        path = (root / asset).resolve()
        if not path.is_relative_to(allowed) or not path.is_file():
            raise BuildError(f'documents[{number}]: missing or unsafe asset {asset!r}')
        raw = path.read_bytes()
        if not raw.startswith(MIME_SIGNATURES[mime]):
            raise BuildError(f'documents[{number}]: file signature does not match {mime}')
        uri = 'data:' + mime + ';base64,' + base64.b64encode(raw).decode('ascii')
        documents.append({('data_uri' if k == 'asset' else k): (uri if k == 'asset' else v)
                          for k, v in doc.items() if k != 'media_type'})
    model['documents'] = documents
    return model


def validate_model(model: dict) -> None:
    """Validate references and identity boundaries, not historical claims."""
    if not isinstance(model, dict):
        raise BuildError('Atlas data must be a JSON object')
    ids: dict[str, set[str]] = {}
    for collection in ('people', 'families', 'sources', 'relationships'):
        records = model.get(collection)
        if not isinstance(records, list):
            raise BuildError(f'{collection} must be an array')
        seen: set[str] = set()
        for record in records:
            key = 'relationship_id' if collection == 'relationships' else 'id'
            ident = record.get(key) if isinstance(record, dict) else None
            if not isinstance(ident, str) or not re.fullmatch(r'[A-Za-z0-9_-]+', ident):
                raise BuildError(f'Invalid {collection} identifier {ident!r}; do not silently normalize identifiers')
            if ident in seen:
                raise BuildError(f'Duplicate {collection} identifier {ident!r}')
            seen.add(ident)
        ids[collection] = seen
    if model.get('default_family') not in ids['families']:
        raise BuildError('default_family must reference an existing family')
    for family in model['families']:
        for role in ('parents', 'children', 'peers'):
            if not isinstance(family.get(role), list):
                raise BuildError(f'{family["id"]}.{role} must be an array')
            for person in family[role]:
                if person not in ids['people']:
                    raise BuildError(f'{family["id"]}.{role} references missing person {person!r}')
        for related in family.get('related', []):
            if related.get('person_id') not in ids['people']:
                raise BuildError(f'{family["id"]}.related references a missing person')
        for parent in family.get('ancestors', []):
            if not isinstance(parent, dict) or parent.get('family_id') not in ids['families']:
                raise BuildError(f'{family["id"]}.ancestors references a missing family')
            if parent.get('through_person_id') not in ids['people']:
                raise BuildError(f'{family["id"]}.ancestors references a missing shared person')
    for relation in model['relationships']:
        for key in ('person_a_id', 'person_b_id'):
            if relation.get(key) not in ids['people']:
                raise BuildError(f'{relation["relationship_id"]}.{key} references a missing person')
    for doc in model.get('documents', []):
        if doc.get('person_id') not in ids['people']:
            raise BuildError('A document references a missing person')
        if not isinstance(doc.get('data_uri'), str):
            raise BuildError('A document has no embedded image after asset resolution')


def load_model(root: Path = ROOT) -> dict:
    """Read the already public presentation model and embed its own public assets."""
    root = Path(root)
    try:
        model = json.loads((root / 'data/atlas.json').read_text(encoding='utf-8'))
    except (OSError, json.JSONDecodeError) as exc:
        raise BuildError(f'Cannot read data/atlas.json: {exc}') from exc
    embed_documents(model, root)
    validate_model(model)
    return model


def build(root: Path = ROOT) -> str:
    root = Path(root)
    src = root / 'src'
    template = (src / 'shell.html').read_text(encoding='utf-8')
    css = '\n'.join((src / name).read_text(encoding='utf-8') for name in CSS_FILES)
    js = '\n;\n'.join((src / name).read_text(encoding='utf-8') for name in JS_FILES)
    for marker in ('/* ATLAS_STYLE */', '/* ATLAS_CODE */', 'ATLAS_DATA'):
        if template.count(marker) != 1:
            raise BuildError(f'src/shell.html must contain exactly one {marker!r} placeholder')
    return template.replace('/* ATLAS_STYLE */', css).replace('/* ATLAS_CODE */', js).replace('ATLAS_DATA', safe_json(load_model(root)))


def write_atomic(output: Path, content: bytes) -> None:
    """Never damage the last valid page when validation or writing fails."""
    output.parent.mkdir(parents=True, exist_ok=True)
    temp: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(prefix='.' + output.name + '.', suffix='.tmp', dir=output.parent, delete=False) as stream:
            temp = Path(stream.name)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        temp.chmod(0o644)
        os.replace(temp, output)
    finally:
        if temp is not None:
            temp.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the committed page is stale; do not write anything')
    parser.add_argument('--output', type=Path, default=ROOT / 'index.html', help='Output path (default: root index.html)')
    args = parser.parse_args()
    try:
        content = build().encode('utf-8')
        output = args.output.resolve()
        if args.check:
            if not output.is_file() or output.read_bytes() != content:
                raise BuildError('Generated page is missing or stale. Run: python scripts/build.py')
        elif not output.is_file() or output.read_bytes() != content:
            write_atomic(output, content)
    except (BuildError, OSError, ValueError) as exc:
        parser.exit(1, f'Build failed: {exc}\n')
    print(json.dumps({'check': args.check, 'bytes': len(content), 'sha256': hashlib.sha256(content).hexdigest()}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
