    @classmethod
    def tearDownClass(cls):
        (QA/'qa.json').write_text(json.dumps({'chrome':cls.browser.version,'checks':cls.evidence,'javascriptErrors':cls.all_errors,'networkRequests':cls.all_requests},ensure_ascii=False,indent=2), encoding='utf-8')
        cls.browser.close();cls.pw.stop()
    def setUp(self):
        self.errors=[];self.requests=[]
        self.context=self.browser.new_context(viewport={'width':1440,'height':918})
        self.context.route('**/*',lambda r:(self.requests.append(r.request.url),r.abort()))
        self.page=self.context.new_page();self.page.on('pageerror',lambda e:self.errors.append(str(e)))
        self.addCleanup(self.context.close)
        enlarge_headless_window(context=self.context, page=self.page)
        self.page.set_content('<style>html,body{margin:0;height:100%}iframe{width:100%;height:100%;border:0;display:block}</style>')
        self.page.evaluate('html=>{let f=document.createElement("iframe");f.sandbox="allow-scripts";f.src=URL.createObjectURL(new Blob([html],{type:"text/html"}));document.body.append(f)}',build.build())
        self.frame=self.page.frames[1];self.frame.wait_for_load_state()
    def tearDown(self):
        self.all_errors.extend(self.errors);self.all_requests.extend(self.requests)
        self.assertEqual(self.errors,[]);self.assertEqual(self.requests,[]);self.context.close()
